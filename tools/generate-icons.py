"""Freeze the approved Lucide outlines as Compose vectors. Run only when updating assets."""
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET
from concurrent.futures import ThreadPoolExecutor
icons = {'ArrowBack':'arrow-left','CropPortrait':'rectangle-vertical','GridView':'grid-2x2','MoreHoriz':'ellipsis','Settings':'settings-2','Check':'check','Undo':'undo-2','DeleteOutline':'trash-2','Image':'images','Folder':'folder','Close':'x','ChevronRight':'chevron-right'}
def load(pair):
    name, slug = pair
    data=urllib.request.urlopen('https://cdn.jsdelivr.net/npm/lucide-static@0.468.0/icons/'+slug+'.svg', timeout=40).read()
    root=ET.fromstring(data); paths=[]
    for el in root:
        tag=el.tag.split('}')[-1];a=el.attrib
        if tag=='path': paths.append(a['d'])
        elif tag=='line': paths.append(f"M{a['x1']},{a['y1']} L{a['x2']},{a['y2']}")
        elif tag in ('polyline','polygon'): paths.append('M'+a['points'].replace(' ',', ',1)+(' Z' if tag=='polygon' else ''))
        elif tag=='circle':
            x,y,r=map(float,(a['cx'],a['cy'],a['r']));paths.append(f'M{x-r},{y} a{r},{r} 0 1,0 {r*2},0 a{r},{r} 0 1,0 {-r*2},0')
        elif tag=='rect':
            x,y,w,h=map(float,(a.get('x',0),a.get('y',0),a['width'],a['height']));r=float(a.get('rx',0));paths.append(f'M{x+r},{y} H{x+w-r} Q{x+w},{y} {x+w},{y+r} V{y+h-r} Q{x+w},{y+h} {x+w-r},{y+h} H{x+r} Q{x},{y+h} {x},{y+h-r} V{y+r} Q{x},{y} {x+r},{y} Z')
    assert paths, slug
    statements='\n'.join('        addPath(pathData=addPathNodes("'+p+'"),fill=null,stroke=SolidColor(Color.Black),strokeLineWidth=1.7f,strokeLineCap=StrokeCap.Round,strokeLineJoin=StrokeJoin.Round)' for p in paths)
    return f'    val {name}: ImageVector = ImageVector.Builder("{slug}",24.dp,24.dp,24f,24f).apply {{\n{statements}\n    }}.build()'
header='''// Lucide 0.468.0; ISC license, see THIRD_PARTY_NOTICES.md. Generated by tools/generate-icons.py.
package io.github.sgrpg.ceye
import androidx.compose.ui.graphics.*
import androidx.compose.ui.graphics.vector.*
import androidx.compose.ui.unit.dp
object CeYeIcons {
'''
out=Path(__file__).resolve().parents[1]/'app/src/main/java/io/github/sgrpg/ceye/CeYeIcons.kt'
out.write_text(header+'\n'.join(ThreadPoolExecutor().map(load, icons.items()))+'\n}\n',encoding='utf-8')
print('Frozen',len(icons),'Lucide vectors')
